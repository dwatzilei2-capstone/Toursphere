-- Fleet & Vehicle Management — Add Vehicle: Cargo / Logistics 2 registration support.
-- Additive and non-destructive: no table is dropped or recreated, no existing vehicle row is
-- converted to cargo, and every passenger value (including vehicles.capacity) is preserved.
-- Idempotent: safe to re-run.

BEGIN;

-- 1) Cargo specifications on vehicles. Existing rows keep service_category = 'Passenger'
--    and receive NULL cargo columns; the default does not rewrite any historical value.
ALTER TABLE vehicles
  ADD COLUMN IF NOT EXISTS service_category    varchar(20) NOT NULL DEFAULT 'Passenger',
  ADD COLUMN IF NOT EXISTS payload_capacity_kg numeric(10,2),
  ADD COLUMN IF NOT EXISTS cargo_volume_m3     numeric(10,3),
  ADD COLUMN IF NOT EXISTS cargo_length_m      numeric(6,2),
  ADD COLUMN IF NOT EXISTS cargo_width_m       numeric(6,2),
  ADD COLUMN IF NOT EXISTS cargo_height_m      numeric(6,2);

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_service_category_check') THEN
    ALTER TABLE vehicles ADD CONSTRAINT vehicles_service_category_check
      CHECK (service_category IN ('Passenger', 'Cargo'));
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_payload_capacity_check') THEN
    ALTER TABLE vehicles ADD CONSTRAINT vehicles_payload_capacity_check
      CHECK (payload_capacity_kg IS NULL OR payload_capacity_kg BETWEEN 0.01 AND 60000);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_cargo_volume_check') THEN
    ALTER TABLE vehicles ADD CONSTRAINT vehicles_cargo_volume_check
      CHECK (cargo_volume_m3 IS NULL OR cargo_volume_m3 BETWEEN 0.001 AND 200);
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicles_cargo_dimension_check') THEN
    ALTER TABLE vehicles ADD CONSTRAINT vehicles_cargo_dimension_check CHECK (
      (cargo_length_m IS NULL AND cargo_width_m IS NULL AND cargo_height_m IS NULL)
      OR (cargo_length_m IS NOT NULL AND cargo_width_m IS NOT NULL AND cargo_height_m IS NOT NULL
          AND cargo_length_m > 0 AND cargo_width_m > 0 AND cargo_height_m > 0));
  END IF;
END $$;

-- Cargo vehicles carry no passenger seat count. Existing passenger rows keep their values.
ALTER TABLE vehicles ALTER COLUMN capacity DROP NOT NULL;

COMMENT ON COLUMN vehicles.service_category IS
  'Passenger = original tour fleet, Cargo = Logistics 2 delivery fleet. Existing rows remain Passenger.';
COMMENT ON COLUMN vehicles.payload_capacity_kg IS
  'Maximum payload capacity in kilograms. NULL for passenger vehicles.';
COMMENT ON COLUMN vehicles.cargo_volume_m3 IS
  'Usable cargo volume in cubic metres. NULL for passenger vehicles.';
COMMENT ON COLUMN vehicles.cargo_length_m IS
  'Cargo bay length in metres; recorded with cargo_width_m and cargo_height_m.';
COMMENT ON COLUMN vehicles.cargo_width_m IS 'Cargo bay width in metres.';
COMMENT ON COLUMN vehicles.cargo_height_m IS 'Cargo bay height in metres.';

-- 2) Configurable fuel types. Adding a row enables a new option; status = 'Inactive' retires
--    one without touching vehicles.fuel_type history.
CREATE TABLE IF NOT EXISTS fuel_types (
  id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name       varchar(40) NOT NULL,
  status     varchar(20) NOT NULL DEFAULT 'Active',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now(),
  CONSTRAINT fuel_types_name_key UNIQUE (name),
  CONSTRAINT fuel_types_status_check CHECK (status IN ('Active', 'Inactive'))
);

COMMENT ON TABLE fuel_types IS 'Configurable fuel options offered by the Add Vehicle form.';

INSERT INTO fuel_types (name, sort_order) VALUES
  ('Diesel', 10), ('Gasoline', 20), ('LPG', 30), ('CNG', 40),
  ('LNG', 50), ('Biodiesel', 60), ('Electric', 70), ('Hybrid', 80)
ON CONFLICT (name) DO NOTHING;

-- 3) Cargo vehicle types are added beside the passenger types, which stay Active for
--    historical records and catalog lookups.
ALTER TABLE vehicle_types
  ADD COLUMN IF NOT EXISTS service_category varchar(20) NOT NULL DEFAULT 'Passenger';

