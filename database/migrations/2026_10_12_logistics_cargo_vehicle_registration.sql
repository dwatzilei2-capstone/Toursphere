BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicle_types_service_category_check') THEN
    ALTER TABLE vehicle_types ADD CONSTRAINT vehicle_types_service_category_check
      CHECK (service_category IN ('Passenger', 'Cargo'));
  END IF;
END $$;

