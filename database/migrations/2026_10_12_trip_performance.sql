BEGIN;
CREATE TABLE trip_performance_evaluations (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id VARCHAR(20) NOT NULL UNIQUE REFERENCES trips(id) ON DELETE RESTRICT,
 driver_id VARCHAR(20) REFERENCES drivers(id) ON DELETE RESTRICT,
 status VARCHAR(20) NOT NULL DEFAULT 'Draft' CHECK(status IN ('Draft','Submitted','Finalized')),
 weights JSONB NOT NULL,
 scores JSONB NOT NULL DEFAULT '{}'::jsonb,
 timing_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
 delay_cause VARCHAR(20) NOT NULL DEFAULT 'Unknown' CHECK(delay_cause IN ('Unknown','External','Driver','None')),
 delay_notes TEXT NOT NULL DEFAULT '',
 overall_score NUMERIC(5,2) CHECK(overall_score BETWEEN 0 AND 100),
 submitted_by INTEGER REFERENCES users(id) ON DELETE RESTRICT,
 submitted_at TIMESTAMPTZ,
 finalized_by INTEGER REFERENCES users(id) ON DELETE RESTRICT,
 finalized_at TIMESTAMPTZ,
 revision INTEGER NOT NULL DEFAULT 1,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(jsonb_typeof(weights)='object' AND jsonb_typeof(scores)='object'),
 CHECK(status<>'Submitted' OR (submitted_by IS NOT NULL AND submitted_at IS NOT NULL)),
 CHECK((status='Finalized')=(finalized_by IS NOT NULL AND finalized_at IS NOT NULL)),
 CHECK(status<>'Finalized' OR overall_score IS NOT NULL)
);
CREATE TABLE trip_performance_evidence (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id VARCHAR(20) NOT NULL REFERENCES trips(id) ON DELETE RESTRICT,
 kind VARCHAR(30) NOT NULL CHECK(kind IN ('Arrival','Delivery Verification','Fuel','Conduct','POD','Supporting Document')),
 criteria JSONB NOT NULL CHECK(jsonb_typeof(criteria)='array'),
 source_table VARCHAR(40), source_id VARCHAR(60),
 snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
 description TEXT NOT NULL CHECK(length(trim(description)) BETWEEN 1 AND 2000),
 stored_filename VARCHAR(100), original_filename VARCHAR(255), mime_type VARCHAR(80), file_size INTEGER,
 sha256 VARCHAR(64),
 added_by INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 verified_by INTEGER REFERENCES users(id) ON DELETE RESTRICT,
 verified_at TIMESTAMPTZ, verification_notes TEXT,
 CHECK((verified_by IS NULL)=(verified_at IS NULL)),
 CHECK((stored_filename IS NULL)=(sha256 IS NULL))
);
CREATE INDEX idx_trip_performance_evidence_trip ON trip_performance_evidence(trip_id);
CREATE INDEX idx_trip_performance_source ON trip_performance_evidence(trip_id,kind,source_table,source_id) WHERE source_id IS NOT NULL;
CREATE TABLE trip_performance_disputes (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 evaluation_id BIGINT NOT NULL REFERENCES trip_performance_evaluations(id) ON DELETE RESTRICT,
 driver_user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
 reason TEXT NOT NULL CHECK(length(trim(reason)) BETWEEN 1 AND 2000),
 evidence_ids JSONB NOT NULL DEFAULT '[]'::jsonb,
 status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK(status IN ('Open','Upheld','Returned for Review')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_by INTEGER REFERENCES users(id) ON DELETE RESTRICT,
 resolved_at TIMESTAMPTZ, resolution TEXT,
 CHECK((status='Open')=(resolved_at IS NULL)),
 CHECK(status='Open' OR (resolved_by IS NOT NULL AND length(trim(resolution)) BETWEEN 1 AND 2000))
);
CREATE UNIQUE INDEX uq_trip_performance_open_dispute ON trip_performance_disputes(evaluation_id) WHERE status='Open';
INSERT INTO system_settings(setting_key,setting_value) VALUES ('trip_performance.weights','{"on_time":25,"completion":25,"safety":20,"fuel":15,"documentation":10,"conduct":5}') ON CONFLICT(setting_key) DO NOTHING;
COMMIT;
