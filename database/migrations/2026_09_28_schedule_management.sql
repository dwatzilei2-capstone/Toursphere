CREATE TABLE IF NOT EXISTS operating_schedules (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    departure_time TIME NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'Active' CHECK (status IN ('Active', 'Inactive')),
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS operating_schedule_days (
    schedule_id INTEGER NOT NULL REFERENCES operating_schedules(id) ON DELETE CASCADE,
    iso_weekday SMALLINT NOT NULL CHECK (iso_weekday BETWEEN 1 AND 7),
    PRIMARY KEY (schedule_id, iso_weekday)
);

CREATE TABLE IF NOT EXISTS scheduled_departures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id INTEGER NOT NULL REFERENCES operating_schedules(id) ON DELETE RESTRICT,
    service_date DATE NOT NULL,
    schedule_name_snapshot VARCHAR(120) NOT NULL,
    departure_time_snapshot TIME NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    status VARCHAR(20) NOT NULL DEFAULT 'Open' CHECK (status IN ('Open', 'Closed', 'Dispatched', 'Completed', 'Cancelled')),
    assigned_vehicle_id VARCHAR(20) REFERENCES vehicles(id) ON DELETE RESTRICT,
    assigned_driver_id VARCHAR(20) REFERENCES drivers(id) ON DELETE RESTRICT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (schedule_id, service_date)
);

ALTER TABLE reservations
