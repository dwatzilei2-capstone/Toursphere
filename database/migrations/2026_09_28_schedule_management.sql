ALTER TABLE reservations
    ADD COLUMN IF NOT EXISTS return_schedule_name VARCHAR(120);

CREATE INDEX IF NOT EXISTS idx_operating_schedule_status_time ON operating_schedules(status, departure_time);
CREATE INDEX IF NOT EXISTS idx_scheduled_departures_date ON scheduled_departures(service_date, departure_time_snapshot);
CREATE INDEX IF NOT EXISTS idx_reservations_departure_schedule ON reservations(departure_schedule_instance_id);
CREATE INDEX IF NOT EXISTS idx_reservations_return_schedule ON reservations(return_schedule_instance_id);

COMMENT ON TABLE operating_schedules IS 'Reusable administrator-configured operating schedule templates.';
COMMENT ON TABLE scheduled_departures IS 'Dated schedule instances with immutable name/time snapshots and shared passenger capacity.';
