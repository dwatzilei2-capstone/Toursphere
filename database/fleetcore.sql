CREATE TABLE route_waypoints (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preset_id  VARCHAR(30) NOT NULL,
  name       VARCHAR(200) NOT NULL,
  lat        DECIMAL(10,6) NOT NULL,
  lng        DECIMAL(10,6) NOT NULL,
  sort_order INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_wp_preset FOREIGN KEY (preset_id) REFERENCES route_presets(id) ON DELETE CASCADE
);

CREATE TABLE route_alternatives (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  preset_id        VARCHAR(30) NOT NULL,
  mode_key         VARCHAR(30) NOT NULL,     
  title            VARCHAR(200) NOT NULL,
  distance         VARCHAR(30) NOT NULL,
  duration         VARCHAR(30) NOT NULL,
  fuel_estimate    VARCHAR(60) NOT NULL,
