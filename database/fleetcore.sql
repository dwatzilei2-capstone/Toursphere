CREATE TABLE roles (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(50)  NOT NULL UNIQUE,
  name          VARCHAR(100) NOT NULL,
  description   VARCHAR(255) DEFAULT NULL
);

CREATE TABLE permissions (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code          VARCHAR(100) NOT NULL UNIQUE,
  name          VARCHAR(150) NOT NULL,
  module        VARCHAR(100) DEFAULT NULL
);

CREATE TABLE role_permissions (
  role_id       INT NOT NULL,
  permission_id INT NOT NULL,
  PRIMARY KEY (role_id, permission_id),
  CONSTRAINT fk_rp_role FOREIGN KEY (role_id) REFERENCES roles(id) ON DELETE CASCADE,
  CONSTRAINT fk_rp_perm FOREIGN KEY (permission_id) REFERENCES permissions(id) ON DELETE CASCADE
);

CREATE TABLE users (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  emp_id        VARCHAR(30)  NOT NULL UNIQUE,
  name          VARCHAR(120) NOT NULL,
  email         VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role_id       INT NOT NULL,
  department    VARCHAR(150) DEFAULT NULL,
  avatar        VARCHAR(500) DEFAULT NULL,
  status        VARCHAR(20) CHECK (status IN ('Active','Inactive')) NOT NULL DEFAULT 'Active',
  created_at    TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES roles(id)
);

 
 
 

CREATE TABLE drivers (
  id                  VARCHAR(20) NOT NULL PRIMARY KEY,    
  user_id             INT DEFAULT NULL,                    
  name                VARCHAR(120) NOT NULL,
  emp_id              VARCHAR(30) DEFAULT NULL,
  phone               VARCHAR(40) DEFAULT NULL,
  license_no          VARCHAR(40) DEFAULT NULL,
  license_class       VARCHAR(100) DEFAULT NULL,
  license_expiration  DATE DEFAULT NULL,
  status              VARCHAR(30) NOT NULL DEFAULT 'Active',
  safety_score        INT NOT NULL DEFAULT 95,
  on_time_rate        DECIMAL(5,2) NOT NULL DEFAULT 97.00,
  fuel_efficiency_score INT NOT NULL DEFAULT 90,
  rating              DECIMAL(3,2) NOT NULL DEFAULT 4.80,
  trip_count          INT NOT NULL DEFAULT 0,
  completed_trips     INT NOT NULL DEFAULT 0,
  cancelled_trips     INT NOT NULL DEFAULT 0,
  department          VARCHAR(150) DEFAULT NULL,
  hrms_status         VARCHAR(200) DEFAULT NULL,
  CONSTRAINT fk_drivers_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
);

CREATE TABLE vehicles (
  id                  VARCHAR(20) NOT NULL PRIMARY KEY,    
  plate_number        VARCHAR(20) NOT NULL UNIQUE,
  type                VARCHAR(60) NOT NULL,
  brand               VARCHAR(60) NOT NULL,
  model               VARCHAR(100) NOT NULL,
  year                INT NOT NULL,
  capacity            INT NOT NULL,
  status              VARCHAR(30) NOT NULL DEFAULT 'Available',
  assigned_driver_id  VARCHAR(20) DEFAULT NULL,
  fuel_type           VARCHAR(30) DEFAULT NULL,
  fuel_capacity       INT DEFAULT NULL,
  current_fuel        INT DEFAULT NULL,
  odometer            INT DEFAULT NULL,
  maintenance_status  VARCHAR(150) DEFAULT NULL,
  next_maintenance    VARCHAR(50) DEFAULT NULL,
  last_maintenance    VARCHAR(50) DEFAULT NULL,
  location            VARCHAR(200) DEFAULT NULL,
  reg_document        VARCHAR(200) DEFAULT NULL,
  insurance_document  VARCHAR(200) DEFAULT NULL,
  ltfrb_permit        VARCHAR(200) DEFAULT NULL,
  total_trips         INT NOT NULL DEFAULT 0,
  total_km            INT NOT NULL DEFAULT 0,
  avg_fuel_km         VARCHAR(20) DEFAULT NULL,
  operating_cost_km   VARCHAR(20) DEFAULT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_vehicles_driver FOREIGN KEY (assigned_driver_id) REFERENCES drivers(id) ON DELETE SET NULL
);

CREATE TABLE reservations (
  id                  VARCHAR(30) NOT NULL PRIMARY KEY,    
  client_name         VARCHAR(150) NOT NULL,
  contact_person      VARCHAR(120) DEFAULT NULL,
  contact_phone       VARCHAR(40) DEFAULT NULL,
  passenger_count     INT NOT NULL,
  origin              VARCHAR(200) NOT NULL,
  destination         VARCHAR(200) NOT NULL,
  departure_date      DATE NOT NULL,
  departure_time      VARCHAR(20) DEFAULT NULL,
  return_date         DATE DEFAULT NULL,
  vehicle_requested   VARCHAR(120) DEFAULT NULL,
  assigned_vehicle_id VARCHAR(20) DEFAULT NULL,
  assigned_driver_id  VARCHAR(20) DEFAULT NULL,
  status              VARCHAR(30) NOT NULL DEFAULT 'Pending',
  trip_type           VARCHAR(120) DEFAULT NULL,
  notes               TEXT DEFAULT NULL,
  estimated_cost      DECIMAL(12,2) DEFAULT NULL,
  cancellation_type   VARCHAR(30) DEFAULT NULL,
  cancellation_reason VARCHAR(120) DEFAULT NULL,
  cancellation_notes  TEXT DEFAULT NULL,
  cancelled_by        INTEGER DEFAULT NULL,
  cancelled_at        TIMESTAMP DEFAULT NULL,
  cancelled_vehicle_id VARCHAR(20) DEFAULT NULL,
  cancelled_driver_id VARCHAR(20) DEFAULT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_res_vehicle FOREIGN KEY (assigned_vehicle_id) REFERENCES vehicles(id) ON DELETE SET NULL,
  CONSTRAINT fk_res_driver FOREIGN KEY (assigned_driver_id) REFERENCES drivers(id) ON DELETE SET NULL,
  CONSTRAINT fk_res_cancelled_by FOREIGN KEY (cancelled_by) REFERENCES users(id) ON DELETE SET NULL,
  CONSTRAINT fk_res_cancelled_vehicle FOREIGN KEY (cancelled_vehicle_id) REFERENCES vehicles(id) ON DELETE SET NULL,
  CONSTRAINT fk_res_cancelled_driver FOREIGN KEY (cancelled_driver_id) REFERENCES drivers(id) ON DELETE SET NULL
);

CREATE TABLE trips (
  id                  VARCHAR(20) NOT NULL PRIMARY KEY,    
  reservation_id      VARCHAR(30) DEFAULT NULL,
  origin              VARCHAR(200) NOT NULL,
  destination         VARCHAR(200) NOT NULL,
  waypoints           VARCHAR(300) DEFAULT NULL,
  vehicle_id          VARCHAR(20) DEFAULT NULL,
  driver_id           VARCHAR(20) DEFAULT NULL,
  passengers          INT DEFAULT NULL,
  scheduled_departure TIMESTAMP DEFAULT NULL,
  actual_departure    TIMESTAMP DEFAULT NULL,
  estimated_arrival   TIMESTAMP DEFAULT NULL,
  actual_arrival      TIMESTAMP DEFAULT NULL,
  distance_km         DECIMAL(6,1) DEFAULT NULL,
  status              VARCHAR(30) NOT NULL DEFAULT 'Scheduled',
  progress_pct        INT NOT NULL DEFAULT 0,
  current_step        VARCHAR(120) DEFAULT NULL,
  fuel_estimate       VARCHAR(60) DEFAULT NULL,
  toll_fee            DECIMAL(10,2) DEFAULT NULL,
  driver_allowance    DECIMAL(10,2) DEFAULT NULL,
  total_cost          DECIMAL(12,2) DEFAULT NULL,
  route_history_id    VARCHAR(30) DEFAULT NULL,
  navigation_active   SMALLINT NOT NULL DEFAULT 0 CHECK (navigation_active IN (0,1)),
  final_odometer      INT DEFAULT NULL,
  vehicle_condition   VARCHAR(40) DEFAULT NULL,
  completion_notes    TEXT DEFAULT NULL,
  created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_trips_reservation FOREIGN KEY (reservation_id) REFERENCES reservations(id) ON DELETE SET NULL,
  CONSTRAINT fk_trips_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id) ON DELETE SET NULL,
  CONSTRAINT fk_trips_driver FOREIGN KEY (driver_id) REFERENCES drivers(id) ON DELETE SET NULL
);

CREATE TABLE trip_timeline (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id      VARCHAR(20) NOT NULL,
  title        VARCHAR(200) NOT NULL,
  event_time   VARCHAR(60) DEFAULT NULL,
  completed    SMALLINT NOT NULL DEFAULT 0,
  active_step  SMALLINT NOT NULL DEFAULT 0,
  sort_order   INT NOT NULL DEFAULT 0,
  CONSTRAINT fk_tl_trip FOREIGN KEY (trip_id) REFERENCES trips(id) ON DELETE CASCADE
);

CREATE TABLE maintenance_orders (
  id             VARCHAR(30) NOT NULL PRIMARY KEY,         
  vehicle_id     VARCHAR(20) NOT NULL,
  service_type   VARCHAR(200) NOT NULL,
  priority       VARCHAR(20) CHECK (priority IN ('Critical','Medium','Low')) NOT NULL DEFAULT 'Medium',
  scheduled_date DATE NOT NULL,
  status         VARCHAR(30) NOT NULL DEFAULT 'Scheduled',
  estimated_cost DECIMAL(12,2) DEFAULT NULL,
  notes          TEXT DEFAULT NULL,
  source_trip_id VARCHAR(20) DEFAULT NULL,
  created_at     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_wo_vehicle FOREIGN KEY (vehicle_id) REFERENCES vehicles(id) ON DELETE CASCADE,
  CONSTRAINT fk_wo_source_trip FOREIGN KEY (source_trip_id) REFERENCES trips(id) ON DELETE SET NULL
);

CREATE TABLE fuel_transactions (
  id              VARCHAR(30) NOT NULL PRIMARY KEY,        
  vehicle_id      VARCHAR(20) NOT NULL,
  driver_id       VARCHAR(20) DEFAULT NULL,
