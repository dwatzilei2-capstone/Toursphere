CREATE TABLE route_presets (
  id                 VARCHAR(30) NOT NULL PRIMARY KEY,     
  name               VARCHAR(200) NOT NULL,
  origin             VARCHAR(200) NOT NULL,
  origin_lat         DECIMAL(10,6) NOT NULL,
  origin_lng         DECIMAL(10,6) NOT NULL,
