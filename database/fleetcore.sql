CREATE TABLE ai_model_registry (
  id                   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  model_id             VARCHAR(50) NOT NULL UNIQUE,           
  version              VARCHAR(20) NOT NULL,                  
  algorithm            VARCHAR(80) NOT NULL,                  
  target_variable      VARCHAR(50) NOT NULL,                  
  training_samples     INT NOT NULL DEFAULT 0,
  validation_samples   INT NOT NULL DEFAULT 0,
  mae                  DECIMAL(8,4) NOT NULL DEFAULT 0.0000,
  rmse                 DECIMAL(8,4) NOT NULL DEFAULT 0.0000,
  r2_score             DECIMAL(6,4) NOT NULL DEFAULT 0.0000,
  feature_list_json    TEXT NOT NULL,
  hyperparameters_json TEXT DEFAULT NULL,
  weights_json         TEXT NOT NULL,
  status               VARCHAR(20) CHECK (status IN ('ColdStart','Experimental','Validated','Deployed','Deprecated')) NOT NULL DEFAULT 'ColdStart',
  deployed_at          TIMESTAMP DEFAULT NULL,
  created_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE ai_route_candidates_log (
  id                    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  log_id                VARCHAR(30) NOT NULL,
  candidate_index       INT NOT NULL DEFAULT 0,
  summary_title         VARCHAR(200) NOT NULL,
  distance_km           DECIMAL(7,2) NOT NULL DEFAULT 0.00,
  duration_mins         INT NOT NULL DEFAULT 0,
  traffic_duration_mins INT NOT NULL DEFAULT 0,
  estimated_fuel_l      DECIMAL(7,2) NOT NULL DEFAULT 0.00,
  toll_cost_est         DECIMAL(10,2) NOT NULL DEFAULT 0.00,
  composite_score       INT NOT NULL DEFAULT 0,
  is_selected           SMALLINT NOT NULL DEFAULT 0,
  created_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT fk_candidate_route_history FOREIGN KEY (log_id) REFERENCES route_history(log_id) ON DELETE CASCADE
);

 
 
 

